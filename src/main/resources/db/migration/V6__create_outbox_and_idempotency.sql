-- V6: transactional outbox + consumer-side idempotency ledger.
--
-- WHY AN OUTBOX
-- Creating an import job and publishing "ImportRequested" to Kafka is a dual write
-- across two systems that share no transaction. If the DB commit succeeds and the
-- Kafka send then fails, the job is stuck in ACCEPTED forever; if the send succeeds
-- and the commit rolls back, the consumer references a job that does not exist.
--
-- Instead the event row is INSERTed in the SAME local transaction as the business
-- change. A poller then publishes unpublished rows. That converts the dual write
-- into "exactly one atomic local write + at-least-once delivery".
--
-- GUARANTEE: at-least-once delivery, not exactly-once. A publisher can crash after
-- Kafka accepted the record but before `published_at` is set, producing a duplicate.
-- Duplicates are absorbed downstream by `processed_events` and by the
-- (user_id, external_ref) unique index on transactions.

CREATE TABLE outbox_events (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      UUID         NOT NULL,
    aggregate_type VARCHAR(50) NOT NULL,
    aggregate_id  VARCHAR(50)  NOT NULL,
    event_type    VARCHAR(80)  NOT NULL,
    topic         VARCHAR(120) NOT NULL,
    partition_key VARCHAR(120) NOT NULL,
    payload       JSONB        NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at  TIMESTAMPTZ  NULL,
    attempts      INTEGER      NOT NULL DEFAULT 0,
    last_error    VARCHAR(1000) NULL,

    CONSTRAINT ck_outbox_attempts CHECK (attempts >= 0)
);

CREATE UNIQUE INDEX uq_outbox_events_event_id ON outbox_events (event_id);

-- The poller's only query: oldest unpublished rows first. A partial index keeps
-- this tiny even when the table has millions of published rows.
CREATE INDEX idx_outbox_unpublished
    ON outbox_events (created_at, id)
    WHERE published_at IS NULL;

-- Consumer-side idempotency: "has this consumer group already applied this event?"
CREATE TABLE processed_events (
    event_id       UUID         NOT NULL,
    consumer_group VARCHAR(120) NOT NULL,
    processed_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (event_id, consumer_group)
);

COMMENT ON TABLE  outbox_events          IS 'Transactional outbox. Rows are written in the same TX as the business change.';
COMMENT ON COLUMN outbox_events.event_id IS 'Stable event identity used for consumer-side idempotency.';
COMMENT ON COLUMN outbox_events.attempts IS 'Publish attempts; a row exceeding the configured limit is reported by /actuator metrics.';
COMMENT ON TABLE  processed_events       IS 'Ledger making at-least-once Kafka delivery effectively once-applied.';
