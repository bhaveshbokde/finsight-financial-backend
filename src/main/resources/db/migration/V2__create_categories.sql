-- V2: expense / income categories.
--
-- A category is either:
--   * a SYSTEM category (user_id IS NULL)  — visible to everybody, read-only; or
--   * a USER category   (user_id NOT NULL) — owned by exactly one user.
--
-- Two partial unique indexes enforce "no duplicate name" in each of those scopes.
-- Postgres treats NULLs as distinct in a plain UNIQUE constraint, which is why a
-- single UNIQUE (user_id, lower(name)) would NOT prevent duplicate system names.

CREATE TABLE categories (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NULL REFERENCES users (id) ON DELETE CASCADE,
    name       VARCHAR(60) NOT NULL,
    type       VARCHAR(10) NOT NULL,
    color      VARCHAR(7)  NULL,
    system     BOOLEAN     NOT NULL DEFAULT FALSE,
    archived   BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version    BIGINT      NOT NULL DEFAULT 0,

    CONSTRAINT ck_categories_type   CHECK (type IN ('INCOME', 'EXPENSE')),
    CONSTRAINT ck_categories_color  CHECK (color IS NULL OR color ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_categories_name   CHECK (length(btrim(name)) > 0),
    -- A system category must not be owned; an owned category must not be system.
    CONSTRAINT ck_categories_system_ownership CHECK (
        (system IS TRUE AND user_id IS NULL) OR (system IS FALSE AND user_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_categories_user_name
    ON categories (user_id, lower(name))
    WHERE user_id IS NOT NULL;

CREATE UNIQUE INDEX uq_categories_system_name
    ON categories (lower(name))
    WHERE user_id IS NULL;

-- Listing a user's selectable categories = their own + all system ones.
CREATE INDEX idx_categories_user_type ON categories (user_id, type) WHERE archived = FALSE;

COMMENT ON TABLE  categories         IS 'Income/expense categories. user_id NULL means a built-in system category.';
COMMENT ON COLUMN categories.archived IS 'Soft-delete flag: archived categories stay referenced by historical transactions.';
