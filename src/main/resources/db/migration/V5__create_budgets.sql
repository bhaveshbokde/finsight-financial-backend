-- V5: monthly budgets.
--
-- A budget is scoped to one calendar month and is either:
--   * OVERALL  (category_id IS NULL) — a cap on total expenses for the month, or
--   * CATEGORY (category_id NOT NULL) — a cap on one category for the month.
--
-- `period_month` always stores the FIRST day of the month; the CHECK makes that
-- invariant impossible to violate from any client, including psql.

CREATE TABLE budgets (
    id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id         BIGINT        NULL REFERENCES categories (id) ON DELETE CASCADE,
    period_month        DATE          NOT NULL,
    amount              NUMERIC(19,4) NOT NULL,
    alert_threshold_pct SMALLINT      NOT NULL DEFAULT 80,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version             BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT ck_budgets_amount    CHECK (amount > 0),
    CONSTRAINT ck_budgets_threshold CHECK (alert_threshold_pct BETWEEN 1 AND 100),
    CONSTRAINT ck_budgets_period    CHECK (date_trunc('month', period_month) = period_month)
);

-- At most one OVERALL budget per user per month...
CREATE UNIQUE INDEX uq_budgets_user_overall_month
    ON budgets (user_id, period_month)
    WHERE category_id IS NULL;

-- ...and at most one budget per (user, category, month).
CREATE UNIQUE INDEX uq_budgets_user_category_month
    ON budgets (user_id, category_id, period_month)
    WHERE category_id IS NOT NULL;

-- Budget-utilisation reports read a whole month for one user.
CREATE INDEX idx_budgets_user_period ON budgets (user_id, period_month DESC);

COMMENT ON TABLE  budgets                     IS 'Monthly spending caps, overall or per category.';
COMMENT ON COLUMN budgets.period_month        IS 'First day of the budget month (enforced by ck_budgets_period).';
COMMENT ON COLUMN budgets.alert_threshold_pct IS 'Utilisation percentage at which the API reports status=WARNING.';
