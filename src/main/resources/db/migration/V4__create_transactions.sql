-- V4: financial transactions.
--
-- Monetary rule: `amount` is ALWAYS a positive magnitude; direction comes from
-- `type` (INCOME | EXPENSE). This removes an entire class of sign bugs in
-- aggregation queries and makes CHECK (amount > 0) possible.
--
-- NUMERIC(19,4) — exact decimal, 4 fractional digits. Never float/double.
--
-- Two distinct "sameness" concepts, deliberately separated:
--   external_ref : an IDEMPOTENCY key. Unique per user. For CSV rows it is
--                  sha256(file_checksum + ':' + row_number), so re-processing the
--                  same file (e.g. a redelivered Kafka message) can never insert
--                  the same row twice. NULL for manually created transactions.
--   dedupe_hash  : a HEURISTIC fingerprint of the business content used to *report*
--                  likely duplicates. Intentionally NOT unique — two identical
--                  coffees on the same day are legitimate.

CREATE TABLE transactions (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id   BIGINT        NULL REFERENCES categories (id) ON DELETE SET NULL,
    import_job_id BIGINT        NULL REFERENCES import_jobs (id) ON DELETE SET NULL,
    type          VARCHAR(10)   NOT NULL,
    amount        NUMERIC(19,4) NOT NULL,
    currency      VARCHAR(3)    NOT NULL DEFAULT 'INR',
    txn_date      DATE          NOT NULL,
    description   VARCHAR(255)  NOT NULL,
    merchant      VARCHAR(120)  NULL,
    notes         VARCHAR(500)  NULL,
    source        VARCHAR(20)   NOT NULL DEFAULT 'MANUAL',
    external_ref  VARCHAR(100)  NULL,
    dedupe_hash   VARCHAR(64)   NOT NULL,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version       BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT ck_transactions_type     CHECK (type IN ('INCOME', 'EXPENSE')),
    CONSTRAINT ck_transactions_amount   CHECK (amount > 0),
    CONSTRAINT ck_transactions_source   CHECK (source IN ('MANUAL', 'CSV_IMPORT')),
    CONSTRAINT ck_transactions_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_transactions_desc     CHECK (length(btrim(description)) > 0),
    CONSTRAINT ck_transactions_dedupe   CHECK (dedupe_hash ~ '^[0-9a-f]{64}$')
);

-- IDEMPOTENCY: the single guarantee that makes import retries safe.
CREATE UNIQUE INDEX uq_transactions_user_external_ref
    ON transactions (user_id, external_ref)
    WHERE external_ref IS NOT NULL;

-- Primary listing: "my transactions, newest first", optionally date-bounded.
-- id DESC is the tiebreaker so keyset/offset paging is deterministic.
CREATE INDEX idx_transactions_user_date ON transactions (user_id, txn_date DESC, id DESC);

-- Category breakdown reports and category filters.
CREATE INDEX idx_transactions_user_category_date ON transactions (user_id, category_id, txn_date);

-- Income/expense totals over a period.
CREATE INDEX idx_transactions_user_type_date ON transactions (user_id, type, txn_date);

-- Duplicate *detection* lookups during CSV import.
CREATE INDEX idx_transactions_user_dedupe ON transactions (user_id, dedupe_hash);

-- "Show me everything this import created" / rollback support.
CREATE INDEX idx_transactions_import_job ON transactions (import_job_id) WHERE import_job_id IS NOT NULL;

COMMENT ON TABLE  transactions              IS 'Income and expense records owned by exactly one user.';
COMMENT ON COLUMN transactions.amount       IS 'Positive magnitude only; direction is carried by `type`.';
COMMENT ON COLUMN transactions.external_ref IS 'Per-user idempotency key. For CSV rows: sha256(file_checksum + '':'' + row_number).';
COMMENT ON COLUMN transactions.dedupe_hash  IS 'Non-unique content fingerprint used to report likely duplicates.';
COMMENT ON COLUMN transactions.txn_date     IS 'Calendar date of the transaction (no time zone). Reports bucket on this column.';
