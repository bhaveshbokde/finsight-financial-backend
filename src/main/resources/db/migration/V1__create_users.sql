-- V1: application users.
--
-- Design notes
--  * BIGINT identity surrogate keys: compact, sequential, good index locality.
--    (UUIDv4 would avoid enumeration but costs 16 bytes and random B-tree inserts;
--     the API never exposes an id belonging to another user, so enumeration is moot.)
--  * Email uniqueness is enforced case-insensitively via a functional index rather
--    than the `citext` extension, because CREATE EXTENSION needs privileges the
--    least-privilege application role deliberately does not have.
--  * `version` backs JPA optimistic locking (@Version).
--  * All timestamps are TIMESTAMPTZ and the application works exclusively in UTC.

CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'ROLE_USER',
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT ck_users_role  CHECK (role IN ('ROLE_USER', 'ROLE_ADMIN')),
    CONSTRAINT ck_users_email CHECK (position('@' IN email) > 1)
);

CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));

COMMENT ON TABLE  users               IS 'Registered FinSight users.';
COMMENT ON COLUMN users.password_hash IS 'BCrypt hash (cost 10). Plain-text passwords are never stored or logged.';
COMMENT ON COLUMN users.version       IS 'Optimistic-locking version managed by Hibernate @Version.';
