-- V3: CSV import jobs.
--
-- Lifecycle:  ACCEPTED -> PROCESSING -> COMPLETED | COMPLETED_WITH_ERRORS | FAILED
--
-- The uploaded bytes are kept in a side table so that `import_jobs` — which is
-- polled and updated frequently — stays narrow. A production system would put the
-- payload in object storage and keep only a pointer here; that trade-off is
-- documented in docs/12-DESIGN-DECISIONS-AND-TRADEOFFS.md.

CREATE TABLE import_jobs (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    original_filename VARCHAR(255) NOT NULL,
    file_checksum     VARCHAR(64)  NOT NULL,
    size_bytes        BIGINT       NOT NULL,
    status            VARCHAR(25)  NOT NULL DEFAULT 'ACCEPTED',
    total_rows        INTEGER      NOT NULL DEFAULT 0,
    imported_rows     INTEGER      NOT NULL DEFAULT 0,
    duplicate_rows    INTEGER      NOT NULL DEFAULT 0,
    failed_rows       INTEGER      NOT NULL DEFAULT 0,
    error_message     VARCHAR(1000) NULL,
    -- created_at/updated_at/version come from AuditableEntity, which ImportJob
    -- extends; all three must exist or Hibernate's schema validation fails at
    -- startup. started_at/completed_at are separate domain timestamps marking
    -- when processing actually began and ended.
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    started_at        TIMESTAMPTZ  NULL,
    completed_at      TIMESTAMPTZ  NULL,
    version           BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT ck_import_jobs_status CHECK (
        status IN ('ACCEPTED', 'PROCESSING', 'COMPLETED', 'COMPLETED_WITH_ERRORS', 'FAILED')
    ),
    CONSTRAINT ck_import_jobs_counts CHECK (
        total_rows >= 0 AND imported_rows >= 0 AND duplicate_rows >= 0 AND failed_rows >= 0
    ),
    CONSTRAINT ck_import_jobs_checksum CHECK (file_checksum ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_import_jobs_size CHECK (size_bytes > 0)
);

-- "My imports, newest first" — the only list query this table serves.
CREATE INDEX idx_import_jobs_user_created ON import_jobs (user_id, created_at DESC, id DESC);
-- Used to tell the caller "you already uploaded this exact file".
CREATE INDEX idx_import_jobs_user_checksum ON import_jobs (user_id, file_checksum);

CREATE TABLE import_payloads (
    import_job_id BIGINT PRIMARY KEY REFERENCES import_jobs (id) ON DELETE CASCADE,
    content       TEXT   NOT NULL
);

CREATE TABLE import_row_errors (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_job_id BIGINT       NOT NULL REFERENCES import_jobs (id) ON DELETE CASCADE,
    row_number    INTEGER      NOT NULL,
    raw_row       VARCHAR(1000) NULL,
    error_code    VARCHAR(50)  NOT NULL,
    message       VARCHAR(500) NOT NULL,

    CONSTRAINT ck_import_row_errors_row CHECK (row_number > 0)
);

CREATE INDEX idx_import_row_errors_job ON import_row_errors (import_job_id, row_number);

COMMENT ON TABLE  import_jobs                IS 'One row per uploaded CSV file; tracks asynchronous processing state.';
COMMENT ON COLUMN import_jobs.file_checksum  IS 'SHA-256 of the uploaded bytes; also the basis of per-row idempotency keys.';
COMMENT ON COLUMN import_jobs.duplicate_rows IS 'Rows skipped because an identical (user, external_ref) transaction already existed.';
COMMENT ON TABLE  import_payloads            IS 'Raw CSV text, kept out of import_jobs so status updates stay cheap.';
